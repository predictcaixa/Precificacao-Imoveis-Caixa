create table if not exists public.avm_imports (
    id text primary key,
    file_name text not null,
    model text not null,
    status text not null check (status in ('processing', 'completed', 'failed')),
    total_rows integer not null check (total_rows >= 0),
    processed_rows integer not null default 0 check (processed_rows >= 0),
    predicted_rows integer not null default 0 check (predicted_rows >= 0),
    error_rows integer not null default 0 check (error_rows >= 0),
    error_message text,
    created_at text not null,
    completed_at text
);

create table if not exists public.avm_import_rows (
    id bigint generated by default as identity primary key,
    import_id text not null references public.avm_imports(id) on delete cascade,
    source_row integer not null check (source_row > 0),
    source_data_json text not null,
    prediction double precision,
    status text not null,
    error_message text,
    unique (import_id, source_row)
);

create index if not exists idx_avm_imports_created_at
    on public.avm_imports (created_at desc);

create index if not exists idx_avm_import_rows_import_id
    on public.avm_import_rows (import_id, source_row);

alter table public.avm_imports enable row level security;
alter table public.avm_import_rows enable row level security;
