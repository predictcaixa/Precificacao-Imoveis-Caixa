from __future__ import annotations

import sqlite3
import sys
import tempfile
import unittest
from pathlib import Path
from types import ModuleType
from unittest.mock import MagicMock, Mock, patch

from scripts import offer_avm_store


class OfferAvmStoreTests(unittest.TestCase):
    def setUp(self):
        self.temporary_directory = tempfile.TemporaryDirectory()
        self.database_path = Path(self.temporary_directory.name) / "uploads.sqlite3"
        offer_avm_store.initialize_store(self.database_path)

    def tearDown(self):
        self.temporary_directory.cleanup()

    def test_backend_name_reflects_postgresql_configuration_without_credentials(self):
        with patch.dict(
            "os.environ", {"AVM_DATABASE_URL": "postgresql://user@localhost/db"}
        ):
            self.assertEqual(offer_avm_store.backend_name(), "postgresql")
        with patch.dict("os.environ", {}, clear=True):
            self.assertEqual(offer_avm_store.backend_name(), "sqlite")

    def test_postgresql_connection_uses_configured_driver_and_dict_rows(self):
        fake_connection = object()
        fake_psycopg = ModuleType("psycopg")
        fake_psycopg.connect = Mock(return_value=fake_connection)
        fake_rows = ModuleType("psycopg.rows")
        fake_rows.dict_row = object()
        with (
            patch.dict(
                "os.environ",
                {"AVM_DATABASE_URL": "postgresql://user@localhost/db"},
            ),
            patch.dict(
                sys.modules,
                {"psycopg": fake_psycopg, "psycopg.rows": fake_rows},
            ),
        ):
            connection = offer_avm_store._connect()
        self.assertIs(connection, fake_connection)
        fake_psycopg.connect.assert_called_once_with(
            "postgresql://user@localhost/db",
            connect_timeout=5,
            row_factory=fake_rows.dict_row,
        )

    def test_postgresql_schema_and_queries_use_postgres_syntax(self):
        connection = MagicMock()
        connection.__enter__.return_value = connection
        with patch.object(offer_avm_store, "_connect", return_value=connection):
            offer_avm_store.initialize_store()
        statements = [call.args[0] for call in connection.execute.call_args_list]
        self.assertTrue(
            any("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql for sql in statements)
        )
        self.assertFalse(any("PRAGMA" in sql for sql in statements))

        offer_avm_store._execute(connection, "SELECT * FROM imports WHERE id = ?", ("id",))
        connection.execute.assert_called_with(
            "SELECT * FROM imports WHERE id = %s", ("id",)
        )
        offer_avm_store._executemany(
            connection, "INSERT INTO imports (id) VALUES (?)", [("id",)]
        )
        cursor = connection.cursor.return_value.__enter__.return_value
        cursor.executemany.assert_called_once_with(
            "INSERT INTO imports (id) VALUES (%s)", [("id",)]
        )

    def test_import_saves_source_rows_predictions_and_deletes_cascade(self):
        import_id = offer_avm_store.create_import(
            "C:\\uploads\\apartamentos.xlsx", "xgboost", 2, self.database_path
        )
        offer_avm_store.append_import_rows(
            import_id,
            [
                {
                    "source_row": 2,
                    "source_data": {"AREA PRIV.": 60, "Valor ITBI.": 400000},
                    "prediction": 450000.0,
                    "status": "estimado · experimental",
                    "error": None,
                },
                {
                    "source_row": 3,
                    "source_data": {"AREA PRIV.": 20, "Valor ITBI.": 100000},
                    "prediction": None,
                    "status": "erro de validação",
                    "error": "área fora do intervalo",
                },
            ],
            self.database_path,
        )
        offer_avm_store.complete_import(import_id, "completed", database_path=self.database_path)

        record = offer_avm_store.get_import(import_id, self.database_path)
        rows = offer_avm_store.get_import_rows(import_id, database_path=self.database_path)
        self.assertEqual(record["status"], "completed")
        self.assertEqual(record["processed_rows"], 2)
        self.assertEqual(record["predicted_rows"], 1)
        self.assertEqual(record["error_rows"], 1)
        self.assertEqual(rows[0]["prediction"], 450000.0)
        self.assertEqual(rows[0]["source_data"]["Valor ITBI."], 400000)
        self.assertTrue(offer_avm_store.delete_import(import_id, self.database_path))
        self.assertIsNone(offer_avm_store.get_import(import_id, self.database_path))
        self.assertEqual(offer_avm_store.get_import_rows(import_id, database_path=self.database_path), [])

    def test_import_cannot_be_completed_before_all_rows_are_saved(self):
        import_id = offer_avm_store.create_import(
            "incompleto.xlsx", "catboost", 1, self.database_path
        )
        with self.assertRaisesRegex(ValueError, "linhas pendentes"):
            offer_avm_store.complete_import(
                import_id, "completed", database_path=self.database_path
            )
        self.assertEqual(
            offer_avm_store.get_import(import_id, self.database_path)["status"],
            "processing",
        )

    def test_duplicate_row_batch_rolls_back_without_incrementing_counts(self):
        import_id = offer_avm_store.create_import(
            "duplicado.xlsx", "random_forest", 2, self.database_path
        )
        duplicate = {
            "source_row": 2,
            "source_data": {"area": 60},
            "prediction": None,
            "status": "erro de validação",
            "error": "linha inválida",
        }
        with self.assertRaises(sqlite3.IntegrityError):
            offer_avm_store.append_import_rows(
                import_id, [duplicate, duplicate], self.database_path
            )
        record = offer_avm_store.get_import(import_id, self.database_path)
        self.assertEqual(record["processed_rows"], 0)
        self.assertEqual(offer_avm_store.get_import_rows(import_id, database_path=self.database_path), [])

    def test_prediction_status_must_match_prediction_value(self):
        import_id = offer_avm_store.create_import(
            "inconsistente.xlsx", "xgboost", 1, self.database_path
        )
        with self.assertRaisesRegex(ValueError, "não correspondem"):
            offer_avm_store.append_import_rows(
                import_id,
                [{
                    "source_row": 2,
                    "source_data": {},
                    "prediction": 500000,
                    "status": "erro de previsão",
                    "error": "falha",
                }],
                self.database_path,
            )


if __name__ == "__main__":
    unittest.main()
