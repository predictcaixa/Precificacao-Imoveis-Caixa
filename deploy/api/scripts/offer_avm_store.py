from __future__ import annotations

import json
import os
import sqlite3
import uuid
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator, TypeAlias

BASE_DIR = Path(__file__).resolve().parents[1]
DATABASE_PATH = Path(
    os.environ.get(
        "AVM_UPLOAD_DB_PATH",
        str(BASE_DIR / "dados" / "avm_uploads.sqlite3"),
    )
).resolve()
IMPORT_MODELS = {"random_forest", "catboost", "xgboost"}
ESTIMATE_STATUSES = {"estimado · experimental", "calculado · oferta × 0,9"}
Connection: TypeAlias = Any


def _database_url() -> str | None:
    return os.environ.get("AVM_DATABASE_URL") or os.environ.get("DATABASE_URL")


def backend_name() -> str:
    return "postgresql" if _database_url() else "sqlite"


def _connect(database_path: Path | None = None) -> Connection:
    database_url = _database_url()
    if database_path is None and database_url:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as error:
            raise RuntimeError(
                "PostgreSQL foi configurado, mas o driver psycopg não está instalado. "
                "Execute: py -3.13 -m pip install -r requirements-api.txt"
            ) from error
        return psycopg.connect(
            database_url,
            connect_timeout=5,
            row_factory=dict_row,
        )

    path = database_path or DATABASE_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path, timeout=30)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    connection.execute("PRAGMA busy_timeout = 30000")
    return connection


@contextmanager
def _managed_connection(
    database_path: Path | None = None,
) -> Iterator[Connection]:
    connection = _connect(database_path)
    try:
        with connection:
            yield connection
    finally:
        connection.close()


def initialize_store(database_path: Path | None = None) -> None:
    connection = _connect(database_path)
    try:
        if isinstance(connection, sqlite3.Connection):
            connection.execute("PRAGMA journal_mode = WAL")
            row_id = "INTEGER PRIMARY KEY"
        else:
            row_id = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        schema = [
            f"""
            CREATE TABLE IF NOT EXISTS avm_imports (
                id TEXT PRIMARY KEY,
                file_name TEXT NOT NULL,
                model TEXT NOT NULL,
                status TEXT NOT NULL CHECK (status IN ('processing', 'completed', 'failed')),
                total_rows INTEGER NOT NULL CHECK (total_rows >= 0),
                processed_rows INTEGER NOT NULL DEFAULT 0 CHECK (processed_rows >= 0),
                predicted_rows INTEGER NOT NULL DEFAULT 0 CHECK (predicted_rows >= 0),
                error_rows INTEGER NOT NULL DEFAULT 0 CHECK (error_rows >= 0),
                error_message TEXT,
                created_at TEXT NOT NULL,
                completed_at TEXT
            )
            """,
            f"""
            CREATE TABLE IF NOT EXISTS avm_import_rows (
                id {row_id},
                import_id TEXT NOT NULL REFERENCES avm_imports(id) ON DELETE CASCADE,
                source_row INTEGER NOT NULL CHECK (source_row > 0),
                source_data_json TEXT NOT NULL,
                prediction REAL,
                status TEXT NOT NULL,
                error_message TEXT,
                UNIQUE(import_id, source_row)
            )
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_avm_imports_created_at
                ON avm_imports(created_at DESC);
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_avm_import_rows_import_id
                ON avm_import_rows(import_id, source_row);
            """,
        ]
        with connection:
            for statement in schema:
                connection.execute(statement)
            if not isinstance(connection, sqlite3.Connection):
                connection.execute(
                    "ALTER TABLE avm_imports ENABLE ROW LEVEL SECURITY"
                )
                connection.execute(
                    "ALTER TABLE avm_import_rows ENABLE ROW LEVEL SECURITY"
                )
    finally:
        connection.close()


def _execute(connection: Connection, query: str, parameters: tuple = ()):
    if not isinstance(connection, sqlite3.Connection):
        query = query.replace("?", "%s")
    return connection.execute(query, parameters)


def _executemany(connection: Connection, query: str, parameters: list[tuple]) -> None:
    if isinstance(connection, sqlite3.Connection):
        connection.executemany(query, parameters)
        return
    with connection.cursor() as cursor:
        cursor.executemany(query.replace("?", "%s"), parameters)


def create_import(
    file_name: str, model: str, total_rows: int, database_path: Path | None = None
) -> str:
    if model not in IMPORT_MODELS:
        raise ValueError("Modelo inválido para registrar a importação.")
    if total_rows < 0:
        raise ValueError("A quantidade de linhas não pode ser negativa.")
    import_id = str(uuid.uuid4())
    with _managed_connection(database_path) as connection:
        _execute(
            connection,
            """
            INSERT INTO avm_imports (id, file_name, model, status, total_rows, created_at)
            VALUES (?, ?, ?, 'processing', ?, ?)
            """,
            (
                import_id,
                Path(file_name).name[:255],
                model,
                total_rows,
                datetime.now(timezone.utc).isoformat(),
            ),
        )
    return import_id


def append_import_rows(
    import_id: str,
    rows: list[dict[str, Any]],
    database_path: Path | None = None,
) -> None:
    for row in rows:
        is_prediction = row["status"] in ESTIMATE_STATUSES
        if is_prediction != (row.get("prediction") is not None):
            raise ValueError("O status e a estimativa da linha não correspondem.")
    encoded_rows = [
        (
            import_id,
            row["source_row"],
            json.dumps(
                row["source_data"],
                ensure_ascii=False,
                allow_nan=False,
                separators=(",", ":"),
            ),
            row.get("prediction"),
            row["status"],
            row.get("error"),
        )
        for row in rows
    ]
    predicted_count = sum(row[4] in ESTIMATE_STATUSES for row in encoded_rows)
    error_count = sum(row[4].startswith("erro") for row in encoded_rows)
    with _managed_connection(database_path) as connection:
        cursor = _execute(
            connection, "SELECT status FROM avm_imports WHERE id = ?", (import_id,)
        )
        imported = cursor.fetchone()
        if imported is None:
            raise KeyError("Importação não encontrada.")
        if imported["status"] != "processing":
            raise ValueError("A importação não está aberta para novos registros.")
        _executemany(
            connection,
            """
            INSERT INTO avm_import_rows (
                import_id, source_row, source_data_json, prediction, status, error_message
            ) VALUES (?, ?, ?, ?, ?, ?)
            """,
            encoded_rows,
        )
        _execute(
            connection,
            """
            UPDATE avm_imports
            SET processed_rows = processed_rows + ?,
                predicted_rows = predicted_rows + ?,
                error_rows = error_rows + ?
            WHERE id = ?
            """,
            (len(encoded_rows), predicted_count, error_count, import_id),
        )


def complete_import(
    import_id: str,
    status: str,
    error: str | None = None,
    database_path: Path | None = None,
) -> None:
    if status not in {"completed", "failed"}:
        raise ValueError("Estado final de importação inválido.")
    with _managed_connection(database_path) as connection:
        imported = _execute(
            connection,
            "SELECT status, total_rows, processed_rows FROM avm_imports WHERE id = ?",
            (import_id,),
        ).fetchone()
        if imported is None:
            raise KeyError("Importação não encontrada ou já finalizada.")
        if imported["status"] != "processing":
            raise KeyError("Importação não encontrada ou já finalizada.")
        if status == "completed" and imported["processed_rows"] != imported["total_rows"]:
            raise ValueError("Não é possível concluir uma importação com linhas pendentes.")
        cursor = _execute(
            connection,
            """
            UPDATE avm_imports
            SET status = ?, error_message = ?, completed_at = ?
            WHERE id = ? AND status = 'processing'
            """,
            (status, error[:2000] if error else None, datetime.now(timezone.utc).isoformat(), import_id),
        )
        if cursor.rowcount == 0:
            raise KeyError("Importação não encontrada ou já finalizada.")


def get_import(import_id: str, database_path: Path | None = None) -> dict[str, Any] | None:
    with _managed_connection(database_path) as connection:
        row = _execute(
            connection,
            """
            SELECT id, file_name, model, status, total_rows, processed_rows,
                   predicted_rows, error_rows, error_message, created_at, completed_at
            FROM avm_imports
            WHERE id = ?
            """,
            (import_id,),
        ).fetchone()
    return dict(row) if row is not None else None


def list_imports(
    limit: int = 50, database_path: Path | None = None
) -> list[dict[str, Any]]:
    with _managed_connection(database_path) as connection:
        rows = _execute(
            connection,
            """
            SELECT id, file_name, model, status, total_rows, processed_rows,
                   predicted_rows, error_rows, error_message, created_at, completed_at
            FROM avm_imports
            ORDER BY created_at DESC
            LIMIT ?
            """,
            (limit,),
        ).fetchall()
    return [dict(row) for row in rows]


def get_import_rows(
    import_id: str,
    offset: int = 0,
    limit: int = 1000,
    database_path: Path | None = None,
) -> list[dict[str, Any]]:
    with _managed_connection(database_path) as connection:
        rows = _execute(
            connection,
            """
            SELECT source_row, source_data_json, prediction, status, error_message
            FROM avm_import_rows
            WHERE import_id = ?
            ORDER BY source_row
            LIMIT ? OFFSET ?
            """,
            (import_id, limit, offset),
        ).fetchall()
    return [
        {
            "source_row": row["source_row"],
            "source_data": json.loads(row["source_data_json"]),
            "prediction": row["prediction"],
            "status": row["status"],
            "error": row["error_message"],
        }
        for row in rows
    ]


def delete_import(import_id: str, database_path: Path | None = None) -> bool:
    with _managed_connection(database_path) as connection:
        cursor = _execute(
            connection, "DELETE FROM avm_imports WHERE id = ?", (import_id,)
        )
        return cursor.rowcount > 0
